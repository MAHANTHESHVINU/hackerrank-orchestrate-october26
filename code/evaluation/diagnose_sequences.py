import importlib.util
import json
import sys
from pathlib import Path

BASE = Path(__file__).resolve().parents[2]
CODE_DIR = BASE / "code"
sys.path.insert(0, str(CODE_DIR))

spec = importlib.util.spec_from_file_location(
    "solution_main", CODE_DIR / "main.py"
)
solution = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = solution
spec.loader.exec_module(solution)

def run():
    identities = solution.load_user_identities()
    audit_log = solution.load_user_audit_log()
    activities = solution.load_system_activity()
    manifest = solution.load_evidence_files()

    (
        email_to_user, user_to_emails, user_to_info, user_to_phones,
        email_hash_to_user, name_to_user, user_to_hashes
    ) = solution.build_identity_maps(identities, audit_log)

    evidence_idx = solution.EvidenceIndex(manifest)
    evidence_dict = {f["file_id"]: f for f in manifest}
    requests = solution.load_sample_requests()
    expected_rows = solution.load_sample_output()

    report = [
        "# Sequence Mismatch Diagnostics",
        "",
        "Generated by diagnose_sequences.py.",
        "Solution code and output.csv were not modified.",
        "",
    ]

    total = 0
    exact = 0
    fields = ("phase", "system_id", "resource_id", "operation", "state")

    for case in requests:
        cid = case["case_id"]
        expected_row = expected_rows.get(cid)
        if not expected_row:
            report.extend([f"## {cid}", "- No expected output found.", ""])
            continue

        expected_steps = json.loads(expected_row["steps_json"])
        email = case["email"].strip().lower()
        uid = solution.resolve_user(email, email_to_user)
        emails = user_to_emails.get(uid, set()) if uid else {email}

        status, predicted = solution.analyze_case(
            case, uid, emails, evidence_idx, evidence_dict,
            user_to_info, user_to_phones, email_hash_to_user, activities
        )

        same = len(expected_steps) == len(predicted)
        differences = []

        for i in range(max(len(expected_steps), len(predicted))):
            if i >= len(expected_steps):
                same = False
                differences.append(f"- Unexpected predicted step {i + 1}.")
                continue
            if i >= len(predicted):
                same = False
                differences.append(f"- Expected step {i + 1} is missing.")
                continue

            exp, pred = expected_steps[i], predicted[i]
            changed = [f for f in fields if exp.get(f) != pred.get(f)]
            if changed:
                same = False
                details = "; ".join(
                    f"{f}: expected={exp.get(f)!r}, predicted={pred.get(f)!r}"
                    for f in changed
                )
                differences.append(f"- Step {i + 1}: {details}")

        total += 1
        if same and expected_steps:
            exact += 1

        report.extend([
            f"## {cid}",
            f"- Expected status: {expected_row['deletion_status']}",
            f"- Predicted status: {status}",
            f"- Expected steps: {len(expected_steps)}",
            f"- Predicted steps: {len(predicted)}",
            f"- Exact sequence match: {'YES' if same and expected_steps else 'NO'}",
        ])
        report.extend(differences or ["- No differences in the five compared fields."])
        report.append("")

    report.extend([
        "## Summary",
        f"- Cases evaluated: {total}",
        f"- Exact non-empty sequence matches: {exact}",
        (
            f"- Exact sequence accuracy: {exact / total * 100:.2f}%"
            if total else "- Exact sequence accuracy: unavailable"
        ),
    ])

    out = CODE_DIR / "evaluation" / "sequence_diagnostics.md"
    out.write_text("\n".join(report) + "\n", encoding="utf-8")
    print(f"Diagnostic report written to: {out}")
    print(f"Cases evaluated: {total}; exact sequence matches: {exact}")

if __name__ == "__main__":
    run()
